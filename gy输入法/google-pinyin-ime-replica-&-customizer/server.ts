import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = 3000;

app.use(express.json());

// API Endpoint for AI-powered Pinyin candidate lookup
app.post('/api/pinyin-ai', async (req, res) => {
  const { pinyin, count = 5 } = req.body;

  if (!pinyin || typeof pinyin !== 'string') {
    return res.status(400).json({ error: 'Pinyin string is required' });
  }

  // Preserve the existing client fallback to its built-in/custom dictionary.
  return res.json({ candidates: null, message: 'Using built-in dictionary.' });
});

async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Server running on http://0.0.0.0:${PORT}`);
  });
}

startServer();
